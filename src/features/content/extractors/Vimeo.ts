import { ArticleExtractionResult } from '@/types';
import { logger } from '@/utils';

import { formatTime, groupTranscriptSegments } from './Youtube';

/*
 * Video pages of vimeo.com: /<id>, /<id>/<hash> of an unlisted video (10 hex digits),
 * and a video opened inside a channel, a group, a showcase or an album
 */
const VIMEO_VIDEO_URL_PATTERN =
  /^https?:\/\/(?:www\.)?vimeo\.com\/(?:channels\/[^/?#]+\/|groups\/[^/?#]+\/videos\/|(?:showcase|album)\/\d+\/video\/)?(\d+)(?:\/([0-9a-f]{10}))?\/?(?:[?#]|$)/;

/* The embed player page assigns its config in an inline script, without a trailing semicolon */
const PLAYER_CONFIG_PREFIX = 'window.playerConfig = ';

/* Auto-generated tracks carry the spoken language with this suffix, e.g. "en-x-autogen" */
const AUTO_GENERATED_SUFFIX = '-x-autogen';

const HTML_ENTITIES: Record<string, string> = {
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  nbsp: ' ',
  lrm: '',
  rlm: '',
};

export interface VimeoTextTrack {
  lang: string;
  url: string;
  kind?: string;
  label?: string;
  provenance?: string;
}

interface VimeoPlayerConfig {
  request?: { text_tracks?: VimeoTextTrack[] };
  video?: { title?: string; url?: string };
}

/**
 * Read the video id and the unlisted hash out of a vimeo.com video URL
 * @param url - The page URL
 * @returns The video id and hash, or null when the URL is not a video page
 */
export const parseVimeoVideoUrl = (url: string): { id: string; hash: string | null } | null => {
  const match = url.match(VIMEO_VIDEO_URL_PATTERN);
  return match ? { id: match[1], hash: match[2] ?? null } : null;
};

/**
 * Tell whether a URL points at a video page of vimeo.com
 * @param url - The URL to test
 * @returns True when the URL points at a video page
 */
export const isVimeoVideoUrl = (url: string): boolean => parseVimeoVideoUrl(url) !== null;

/**
 * Read the player hash from the page's player meta tag. The page is rendered client side,
 * so the tag is used only when it still points at the video in the URL
 * @param document - The document of the video page
 * @param id - The video id from the URL
 * @returns The hash, or null when the tag is missing or belongs to another video
 */
const getPlayerHash = (document: Document, id: string): string | null => {
  const content = document.querySelector('meta[name="twitter:player"]')?.getAttribute('content');
  if (!content) return null;
  try {
    const playerUrl = new URL(content);
    if (playerUrl.pathname !== `/video/${id}`) return null;
    return playerUrl.searchParams.get('h');
  } catch {
    return null;
  }
};

/**
 * Parse the player config out of the HTML of the embed player page
 * @param html - The HTML of player.vimeo.com/video/<id>
 * @returns The config, or null when the page has none
 */
export const parsePlayerConfig = (html: string): VimeoPlayerConfig | null => {
  const start = html.indexOf(PLAYER_CONFIG_PREFIX);
  if (start < 0) return null;
  const end = html.indexOf('</script>', start);
  if (end < 0) return null;
  try {
    return JSON.parse(
      html
        .slice(start + PLAYER_CONFIG_PREFIX.length, end)
        .trim()
        .replace(/;$/, '')
    );
  } catch {
    return null;
  }
};

const isAutoGenerated = (track: VimeoTextTrack): boolean => track.provenance === 'ai_generated' || track.lang.endsWith(AUTO_GENERATED_SUFFIX);

const baseLanguage = (lang: string): string => lang.replace(AUTO_GENERATED_SUFFIX, '').split('-')[0].toLowerCase();

/**
 * Pick the caption track to summarize. Uploaded tracks win over auto-generated ones;
 * among uploaded tracks the browser language comes first, then the spoken language
 * (the language of the auto-generated track), then the first track
 * @param tracks - The text tracks of the player config
 * @param browserLanguage - The language of the browser, e.g. "en-US"
 * @returns The track, or null when the video has none
 */
export const selectTextTrack = (tracks: VimeoTextTrack[], browserLanguage: string): VimeoTextTrack | null => {
  const uploaded = tracks.filter(track => !isAutoGenerated(track));
  const generated = tracks.find(isAutoGenerated) ?? null;
  if (uploaded.length === 0) return generated;

  const spokenLanguage = generated ? baseLanguage(generated.lang) : null;
  return (
    uploaded.find(track => baseLanguage(track.lang) === baseLanguage(browserLanguage)) ??
    uploaded.find(track => baseLanguage(track.lang) === spokenLanguage) ??
    uploaded[0]
  );
};

/**
 * Parse a WebVTT timestamp
 * @param timestamp - The timestamp in format "HH:MM:SS.mmm" or "MM:SS.mmm"
 * @returns The number of seconds
 */
export const parseVttTimestamp = (timestamp: string): number => {
  const match = timestamp.match(/^(?:(\d+):)?(\d{2}):(\d{2})\.(\d{3})/);
  if (!match) return 0;
  const [, hours, minutes, seconds, milliseconds] = match;
  return Number(hours ?? 0) * 3600 + Number(minutes) * 60 + Number(seconds) + Number(milliseconds) / 1000;
};

const decodeEntities = (text: string): string =>
  text.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (entity, name: string) => {
    if (name[0] === '#') {
      const isHex = name[1].toLowerCase() === 'x';
      return String.fromCodePoint(parseInt(name.slice(isHex ? 2 : 1), isHex ? 16 : 10));
    }
    return HTML_ENTITIES[name.toLowerCase()] ?? entity;
  });

/**
 * Parse the cues of a WebVTT file
 * @param vtt - The WebVTT file
 * @returns The cues with their start in seconds and their text without markup
 */
export const parseVtt = (vtt: string): { start: number; text: string }[] =>
  vtt
    .replace(/\r\n?/g, '\n')
    .split(/\n{2,}/)
    .flatMap(block => {
      const lines = block.split('\n');
      const timingIndex = lines.findIndex(line => line.includes('-->'));
      if (timingIndex < 0) return [];
      /* Tags are removed before decoding, so that an escaped "<" is kept as text */
      const text = decodeEntities(
        lines
          .slice(timingIndex + 1)
          .join(' ')
          .replace(/<[^>]*>/g, '')
      )
        .replace(/\s+/g, ' ')
        .trim();
      if (!text) return [];
      return [{ start: parseVttTimestamp(lines[timingIndex].trim()), text }];
    });

/**
 * Extract the captions of a Vimeo video.
 * The page itself has no transcript, and the player config endpoint refuses requests without
 * the signature the page computes, so the captions are read from the embed player page instead.
 * @param url - The URL of the video page
 * @param document - The document of the video page
 * @returns The extraction result
 */
export async function extractVimeo(url: string, document: Document): Promise<ArticleExtractionResult> {
  try {
    const video = parseVimeoVideoUrl(url);
    if (!video) {
      throw new Error('Could not extract video ID from URL');
    }
    logger.debug('🎞️', '[Vimeo.ts]', '[extractVimeo]', 'Extracting Vimeo captions', video.id);

    const hash = video.hash ?? getPlayerHash(document, video.id);
    const playerUrl = `https://player.vimeo.com/video/${video.id}${hash ? `?h=${hash}` : ''}`;
    /*
     * The player is on another origin, so its cookies are sent only on request. Unlocking a
     * password-protected video sets a cookie, without which the player returns the password form
     */
    const playerResponse = await fetch(playerUrl, { credentials: 'include' });
    if (!playerResponse.ok) {
      throw new Error(`The player page returned ${playerResponse.status}`);
    }
    const config = parsePlayerConfig(await playerResponse.text());
    if (!config) {
      throw new Error('Player config not found');
    }

    const track = selectTextTrack(config.request?.text_tracks ?? [], navigator.language);
    if (!track) {
      throw new Error('The video has no captions');
    }
    const vttResponse = await fetch(new URL(track.url, playerUrl).href);
    if (!vttResponse.ok) {
      throw new Error(`The captions returned ${vttResponse.status}`);
    }
    const segments = groupTranscriptSegments(parseVtt(await vttResponse.text()));
    if (segments.length === 0) {
      throw new Error('The captions are empty');
    }

    /* An unlisted video opens only with its hash, so a hash in the URL is kept in the links */
    const videoUrl = video.hash ? `https://vimeo.com/${video.id}/${video.hash}` : config.video?.url || `https://vimeo.com/${video.id}`;
    const content = segments
      .map(segment => `[${formatTime(segment.start)}](${videoUrl}#t=${Math.floor(segment.start)}s) ${segment.texts.join(' ')}`)
      .join('\n');

    return {
      isSuccess: true,
      title: config.video?.title?.trim() || null,
      url: url,
      content,
      error: null,
    };
  } catch (error) {
    logger.error('🎞️', '[Vimeo.ts]', '[extractVimeo]', 'Error extracting Vimeo captions', error);
    return {
      isSuccess: false,
      title: null,
      url: url,
      content: null,
      error: error instanceof Error ? error : new Error('An error occurred'),
    };
  }
}
